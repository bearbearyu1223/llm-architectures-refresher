def the_router_is_tiny(rep: Report, model) -> None:
    router = [p for n, p in model.named_parameters() if ".mlp.gate." in n]
    total = sum(p.numel() for p in model.parameters())
    n_router = sum(p.numel() for p in router)
    n_exp, top_k, layers = _cfg(model)

    rep.kv("router matrices", f"{len(router)} (one per layer)")
    rep.kv("shape of each", tuple(router[0].shape))
    rep.kv("router parameters", f"{n_router / 1e6:.2f}M")
    rep.kv("as a share of the model", f"{100 * n_router / total:.3f}%")
    rep.kv("router bytes (bf16)", f"{n_router * 2 / MIB:.1f} MiB")
    # Everything that is not the router -- experts, attention, embeddings. Not
    # labelled "expert bytes": that would assert more than the number measures.
    rep.kv("everything else (bf16)", f"{(total - n_router) * 2 / GIB:.2f} GiB")
    rep.takeaway(
        "One matrix per layer, 0.03% of the parameters, decides how the other "
        "93% are spent on every token."
    )


# ---------------------------------------------------------------------------
# 3. One token, routed
# ---------------------------------------------------------------------------


@torch.no_grad()
def route(model, ids: torch.Tensor) -> torch.Tensor:
    """Router logits for every token and layer.

    Returns a ``(layers, tokens, experts)`` float32 tensor. Computed on CPU in
    float32 after the forward pass so that the printed weights do not depend on
    which backend ran the matmuls.
    """
    out = model(ids, output_router_logits=True)
    stacked = torch.stack([r.float().cpu() for r in out.router_logits])
    return stacked.reshape(stacked.shape[0], ids.shape[1], -1)


def one_token_routed(
    rep: Report, model, tok, logits: torch.Tensor, ids: torch.Tensor
) -> list[int]:
    """Walk the routing arithmetic for a single token at a single layer."""
    n_exp, top_k, layers = _cfg(model)
    # pos=1, layer=0 is chosen, not arbitrary: a reader adds the eight printed
    # weights and expects the printed total. Of the 1488 (layer, position) pairs
    # in this passage, 676 reconcile exactly at 4 decimal places and this is one
    # of them. Do not "tidy" this constant -- see the walkthrough in the post.
    pos = 1
    layer = 0
    token_text = tok.decode(ids[0, pos : pos + 1])

    row = logits[layer, pos]
    weights = torch.softmax(row, dim=-1)
    top_w, top_e = torch.topk(weights, top_k)

    rep.kv("token", f"{pos} = {token_text!r}")
    rep.kv("layer", layer)
    rep.kv("router output", f"{n_exp} logits -> softmax -> top-{top_k}")
    rep.blank()
    rep.table(
        ["rank", "expert", "logit", "softmax weight"],
        [
            [i + 1, int(e), f"{row[e]:+.4f}", f"{w:.4f}"]
            for i, (w, e) in enumerate(zip(top_w.tolist(), top_e.tolist()))
        ],
    )
    kept = top_w.sum().item()
    rep.blank()
    rep.kv(f"sum of the {top_k} kept weights", f"{kept:.4f}")
    rep.kv(f"sum of all {n_exp} weights", f"{weights.sum().item():.4f}")
    rep.kv("discarded by the top-k cut", f"{1 - kept:.4f}")
    rep.kv("renormalized? (norm_topk_prob)", model.config.norm_topk_prob)
    rep.takeaway(
        f"The kept weights sum to {kept:.4f}, not 1. OLMoE does not renormalize "
        f"after the cut, so how much probability the router left behind becomes "
        f"a scale on the layer's output."
    )
    return [int(e) for e in top_e.tolist()], kept


def routing_depth_profile(rep: Report, model, logits: torch.Tensor, tok, ids: torch.Tensor) -> None:
    """The same token's top-1 expert at every layer — routing is per layer."""
    n_exp, top_k, layers = _cfg(model)
    pos = 1
    rows = []
    for layer in range(layers):
        w = torch.softmax(logits[layer, pos], dim=-1)
        top_w, top_e = torch.topk(w, top_k)
        rows.append(
            [
                layer,
                int(top_e[0]),
                f"{top_w[0]:.4f}",
                f"{top_w.sum():.4f}",
                f"{top_w[0] / top_w.sum():.2f}",
            ]
        )
    rep.table(["layer", "top-1 expert", "its weight", "kept total", "share"], rows)
    rep.takeaway(
        "One token is routed independently at every layer, so it visits "
        f"{layers} separate committees of {top_k} on its way through the model."
    )


# ---------------------------------------------------------------------------
# 4. What the router learns
# ---------------------------------------------------------------------------


def _topk_idx(logits: torch.Tensor, top_k: int) -> torch.Tensor:
    """Chosen experts per (layer, token): ``(layers, tokens, top_k)``."""
    return torch.topk(logits, top_k, dim=-1).indices


def _usage_from_idx(idx: torch.Tensor, n_exp: int) -> torch.Tensor:
    """Per-layer expert usage distribution: (layers, experts), rows sum to 1."""
    counts = torch.zeros(idx.shape[0], n_exp)
    for layer in range(idx.shape[0]):
        counts[layer] = torch.bincount(idx[layer].reshape(-1), minlength=n_exp).float()
    return counts / counts.sum(dim=-1, keepdim=True)


def _usage(logits: torch.Tensor, top_k: int, n_exp: int) -> torch.Tensor:
    return _usage_from_idx(_topk_idx(logits, top_k), n_exp)


def _tv(a: torch.Tensor, b: torch.Tensor) -> torch.Tensor:
    """Total variation distance per layer. 0 = identical usage, 1 = disjoint."""
    return 0.5 * (a - b).abs().sum(dim=-1)


def what_the_router_learns(
    rep: Report, model, tok
) -> tuple[dict[str, torch.Tensor], dict[str, tuple[torch.Tensor, torch.Tensor]]]:
    """Does expert choice depend on what kind of text the token belongs to?

    A raw distance between two passages proves nothing on its own: two samples
    drawn from the *same* distribution differ too, and these passages are only a
    hundred tokens long. So this measures a noise floor first -- the distance
    between two halves of the same passage -- and reports the cross-domain
    distances against it.
    """
    n_exp, top_k, layers = _cfg(model)
    usage: dict[str, torch.Tensor] = {}
    halves: dict[str, tuple[torch.Tensor, torch.Tensor]] = {}
    rows = []
    for name, text in DOMAINS.items():
        ids = tok(text, return_tensors="pt").input_ids.to(model.device)
        idx = _topk_idx(route(model, ids), top_k)
        usage[name] = _usage_from_idx(idx, n_exp)
        mid = idx.shape[1] // 2
        halves[name] = (
            _usage_from_idx(idx[:, :mid], n_exp),
            _usage_from_idx(idx[:, mid:], n_exp),
        )
        rows.append([name, ids.shape[1]])
    rep.table(["passage", "tokens"], rows)

    floor = torch.stack([_tv(a, b) for a, b in halves.values()]).mean(dim=0)
    rep.blank()
    rep.note("Total variation distance between expert-usage distributions:")
    rep.note("0.00 = the two samples used the experts identically.")
    rep.note("The first row is the noise floor -- two halves of the SAME")
    rep.note("passage, which differ only by sampling. Read every other row")
    rep.note("against it.")
    rep.blank()

    show = [0, layers // 2, layers - 1]
    pairs = [("prose", "code"), ("prose", "math"), ("code", "math")]
    table = [
        ["same passage, split"] + [f"{floor[i]:.3f}" for i in show] + [f"{floor.mean():.3f}"]
    ]
    for a, b in pairs:
        d = _tv(usage[a], usage[b])
        table.append(
            [f"{a} vs {b}"] + [f"{d[i]:.3f}" for i in show] + [f"{d.mean():.3f}"]
        )
    rep.table(["comparison"] + [f"layer {i}" for i in show] + ["mean"], table)

    cross = torch.stack([_tv(usage[a], usage[b]) for a, b in pairs]).mean(dim=0)
    rep.blank()
    rep.kv("noise floor, mean over layers", f"{floor.mean():.3f}")
    rep.kv("cross-domain, mean over layers", f"{cross.mean():.3f}")
    rep.kv("cross-domain over noise floor", f"{cross.mean() / floor.mean():.2f}x")

    # The most domain-skewed expert in the deepest layer. Reported as two shares
    # rather than a ratio: the prose share is often exactly zero, and a ratio
    # against zero is an artifact of whatever epsilon you added, not a finding.
    last = layers - 1
    code_u, prose_u = usage["code"][last], usage["prose"][last]
    expert = int((code_u - prose_u).argmax())
    rep.blank()
    rep.kv(f"most code-leaning expert (layer {last})", expert)
    rep.kv("  share of code routing slots", f"{100 * code_u[expert]:.2f}%")
    rep.kv("  share of prose routing slots", f"{100 * prose_u[expert]:.2f}%")
    rep.kv("  an even share would be", f"{100 / n_exp:.2f}%")
    rep.kv("experts unused by prose but used by code", int(((prose_u == 0) & (code_u > 0)).sum()))

    rep.blank()
    rep.kv("noise floor, first layer", f"{floor[0]:.3f}")
    rep.kv("cross-domain, first layer", f"{cross[0]:.3f}")
    rep.kv("noise floor, last layer", f"{floor[-1]:.3f}")
    rep.kv("cross-domain, last layer", f"{cross[-1]:.3f}")
    rep.takeaway(
        f"Two halves of one passage differ by {floor.mean():.2f}; two different "
        f"kinds of text differ by {cross.mean():.2f}, "
        f"{cross.mean() / floor.mean():.1f}x as much. Expert choice tracks the "
        f"kind of text, and the gap widens with depth."
    )
    return usage, halves


