def load_balance(rep: Report, model, logits: torch.Tensor) -> torch.Tensor:
    n_exp, top_k, layers = _cfg(model)
    usage = _usage(logits, top_k, n_exp)
    even = 1.0 / n_exp

    rows = []
    for layer in (0, layers // 2, layers - 1):
        u = usage[layer]
        rows.append(
            [
                layer,
                f"{100 * u.max():.2f}%",
                f"{100 * u.min():.2f}%",
                f"{u.max() / even:.2f}x",
                f"{(u.std() / u.mean()):.2f}",
            ]
        )
    rep.table(
        ["layer", "busiest", "quietest", "busiest vs even", "coeff of var"], rows
    )
    rep.blank()
    rep.kv("even share would be", f"{100 * even:.2f}%")
    rep.kv("router_aux_loss_coef", model.config.router_aux_loss_coef)
    rep.kv("experts never used (last layer)", int((usage[-1] == 0).sum()))
    rep.takeaway(
        "Nothing makes the experts equally popular by construction; a balance "
        "penalty during training is what keeps one expert from swallowing the "
        "traffic and the rest from starving."
    )
    return usage


