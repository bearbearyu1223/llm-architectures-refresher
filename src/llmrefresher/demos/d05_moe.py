def what_the_final_norm_does(rep: Report, model, tok, ids: torch.Tensor, pos: int = 1) -> None:
    """RMSNorm, applied by hand to a real token, and why the model needs it.

    Mirrors the model's own arithmetic (x * rsqrt(mean(x^2) + eps), then the
    learned per-dimension scale) so the comparison is exact, and measures how far
    the residual stream's size drifts between the first layer and the final norm.
    """
    import copy

    norm = model.model.norm
    cap = {}
    hooks = [
        norm.register_forward_pre_hook(lambda mod, a: cap.__setitem__("h", a[0].detach())),
        model.model.layers[0].register_forward_pre_hook(lambda mod, a: cap.__setitem__("h0", a[0].detach())),
    ]
    try:
        with torch.no_grad():
            model(ids)
    finally:
        for h in hooks:
            h.remove()

    h = cap["h"][0, pos].float().cpu()
    eps = norm.variance_epsilon
    gamma = norm.weight.detach().float().cpu()
    rms_in = h.pow(2).mean().sqrt()
    unit = h * torch.rsqrt(h.pow(2).mean() + eps)
    by_hand = gamma * unit
    with torch.no_grad():
        from_model = copy.deepcopy(norm).float().cpu()(h[None])[0]

    def rms_per_token(x: torch.Tensor) -> torch.Tensor:
        return x[0].float().pow(2).mean(dim=-1).sqrt()

    rep.note(f"The final norm, applied to {tok.decode(ids[0, pos:pos + 1])!r} after the last layer:")
    rep.blank()
    rep.kv("gamma, one scale per dimension", f"shape {tuple(norm.weight.shape)}")
    rep.kv("epsilon", f"{eps:.0e}")
    rep.kv("RMS of the vector coming in", f"{rms_in:.4f}")
    rep.kv("after dividing by its RMS", f"{unit.pow(2).mean().sqrt():.4f}")
    rep.kv("after multiplying by gamma", f"{by_hand.pow(2).mean().sqrt():.4f}")
    rep.kv("gamma smallest / median / largest", f"{gamma.min():.4f} / {gamma.median():.4f} / {gamma.max():.4f}")
    rep.kv("formula by hand == model's norm?", f"{'yes' if torch.equal(by_hand, from_model) else 'no'} (fp32)")
    rep.blank()
    rep.kv("median token RMS entering layer 0", f"{rms_per_token(cap['h0']).median():.4f}")
    rep.kv("median entering the final norm", f"{rms_per_token(cap['h']).median():.4f}")


def why_this_many_experts(rep: Report, model) -> None:
    """Why 64 and 8, rather than 8 and 2?

    The two numbers are not independent, and neither is arbitrary. top_k times
    the expert width is the FFN arithmetic a token actually does, and OLMoE sets
    it to exactly the width a dense model of the same shape would use. The count
    then buys capacity and combinations on top of that fixed budget.
    """
    from math import comb

    n_exp, top_k, layers = _cfg(model)
    hid = model.config.hidden_size
    inter = model.config.intermediate_size
    active_w = top_k * inter
    total_w = n_exp * inter

    rep.kv("model width (hidden_size)", hid)
    rep.kv("one expert's width", inter)
    rep.kv("  as a multiple of the model width", f"{inter / hid:.2f}x")
    rep.kv(f"width actually used per token ({top_k} x {inter})", active_w)
    rep.kv("  as a multiple of the model width", f"{active_w / hid:.2f}x")
    rep.kv(f"width held in total ({n_exp} x {inter})", total_w)
    rep.kv("  as a multiple of the model width", f"{total_w / hid:.2f}x")
    rep.kv("capacity over compute", f"{n_exp / top_k:.0f}x")
    rep.blank()
    rep.note("A dense FFN is conventionally 4x the model width. Per token this")
    rep.note("model does exactly that much FFN arithmetic -- while holding 8x it.")
    rep.blank()

    # Same total capacity, same per-token arithmetic, different granularity.
    rep.note("Same total width, same width used per token, split four ways:")
    rep.blank()
    rows = []
    for k in (1, 2, 4, top_k):
        width = active_w // k          # same arithmetic per token, split k ways
        e = total_w // width              # same total capacity, so this many of them
        rows.append([e, width, k, f"{comb(e, k):,}"])
    rep.table(["experts", "each of width", "used per token", "possible combinations"], rows)
    rep.takeaway(
        f"Every row costs the same to store and the same to run. Splitting the "
        f"same budget into {n_exp} pieces instead of 8 turns {comb(8, 1)} possible "
        f"expert combinations into {comb(n_exp, top_k):,}, which is what the "
        f"count is really buying."
    )


