def figure_where_the_weights_are(rep_counts: dict, theme: Theme) -> Path:
    """Ink measures the quantity: one bar, split by role."""
    fig, ax = plt.subplots(figsize=(9.5, 2.9))
    total = sum(rep_counts.values())
    order = sorted(rep_counts.items(), key=lambda kv: -kv[1])
    small = [r for r, n in order if 100 * n / total <= 8]
    left = 0.0
    for i, (role, n) in enumerate(order):
        share = 100 * n / total
        fill = theme.ramp[5] if role == "experts" else theme.ramp[max(0, 3 - i)]
        ax.barh([0], [share], left=[left], height=0.55, color=fill,
                edgecolor=theme.surface, linewidth=1.2)
        if share > 8:
            ax.text(left + share / 2, 0, f"{role}\n{share:.1f}%", ha="center",
                    va="center", fontsize=11, color=ink_for(fill))
        else:
            # Too narrow to label inside, and every small segment is crowded into
            # the last few percent of the bar -- so labels go on a spread-out row
            # below with a leader back to the segment they name.
            pct = f"{share:.1f}%" if share >= 0.1 else f"{share:.3f}%"
            slot = small.index(role)
            label_x = 34 + 22 * slot
            y_txt = -0.62 if slot % 2 == 0 else -0.95
            ax.annotate(
                f"{role}  {pct}",
                xy=(left + share / 2, -0.30),
                xytext=(label_x, y_txt),
                ha="center", va="center", fontsize=9, color=theme.secondary,
                arrowprops=dict(arrowstyle="-", color=theme.axis, lw=0.8,
                                shrinkA=2, shrinkB=2),
            )
        left += share
    ax.set_xlim(0, 100); ax.set_ylim(-1.25, 0.45)
    ax.set_yticks([]); ax.set_xlabel("share of all parameters (%)")
    ax.grid(False)
    for s in ("left", "right", "top"):
        ax.spines[s].set_visible(False)
    ax.set_title("Where OLMoE-1B-7B's 6.9B parameters live", color=theme.ink)
    fig.tight_layout()
    return save_both(fig, SLUG, "weight-census", theme)


def figure_specialization(
    usage: dict[str, torch.Tensor],
    halves: dict[str, tuple[torch.Tensor, torch.Tensor]],
    theme: Theme,
) -> Path:
    """Expert usage per domain in the last layer — the specialization claim.

    The top two rows are the two halves of the *same* prose passage. They are
    what sampling noise looks like, and they are in the figure so the reader can
    tell the cross-domain rows apart from it by eye rather than on trust.
    """
    from ..plotting import sequential_cmap

    last = usage["prose"].shape[0] - 1
    rows = [
        ("prose, 1st half", halves["prose"][0][last]),
        ("prose, 2nd half", halves["prose"][1][last]),
        ("code", usage["code"][last]),
        ("math", usage["math"][last]),
    ]
    names = [n for n, _ in rows]
    data = torch.stack([v for _, v in rows]).numpy()

    fig, ax = plt.subplots(figsize=(10.5, 3.3))
    im = ax.imshow(data * 100, aspect="auto", cmap=sequential_cmap(theme),
                   interpolation="nearest")
    ax.set_yticks(range(len(names)), names)
    # Separate the noise-floor pair from the cross-domain rows.
    ax.axhline(1.5, color=theme.surface, lw=3.0)
    ax.set_xlabel(f"expert (layer {last})")
    ax.set_title("The same 64 experts, used differently by different text",
                 color=theme.ink)
    ax.axhline(1.5, color=theme.ink, lw=1.0)
    ax.grid(False)
    cb = fig.colorbar(im, ax=ax, pad=0.015)
    cb.set_label("% of that passage's routing slots", color=theme.secondary)
    cb.ax.tick_params(colors=theme.muted)
    cb.outline.set_visible(False)
    fig.tight_layout()
    return save_both(fig, SLUG, "specialization", theme)


def figure_batch_collapse(curve: list[tuple[int, float]], n_exp: int, theme: Theme) -> Path:
    """Experts needed against tokens processed together."""
    fig, ax = plt.subplots(figsize=(8.5, 4.6))
    xs = [c[0] for c in curve]
    ys = [c[1] for c in curve]
    ax.axhline(n_exp, color=theme.muted, lw=1.2, ls="--")
    ax.text(xs[0], n_exp - 2.5, f"all {n_exp} experts", fontsize=9.5,
            color=theme.secondary, va="top")
    ax.plot(xs, ys, marker="o", color=theme.series[0], label="experts actually needed")
    ax.plot(xs, [min(n_exp, 8 * x) for x in xs], marker="", ls=":",
            color=theme.series[1], label="if no two tokens ever agreed")
    ax.set_xscale("log", base=2)
    ax.set_xticks(xs, [str(x) for x in xs])
    ax.set_xlabel("tokens processed together")
    ax.set_ylabel("distinct experts required")
    ax.set_ylim(0, n_exp + 6)
    ax.set_title("Per-token sparsity does not survive batching", color=theme.ink)
    ax.legend(labelcolor=theme.secondary)
    fig.tight_layout()
    return save_both(fig, SLUG, "batch-collapse", theme)


def make_figures(
    rep: Report, model, counts: dict, usage: dict, halves: dict,
    curve: list, chosen: list[int],
) -> None:
    n_exp, _, _ = _cfg(model)
    written = []
    for theme in THEMES:
        with styled(theme):
            written.append(figure_block(model, chosen, theme))
            written.append(figure_where_the_weights_are(counts, theme))
            written.append(figure_specialization(usage, halves, theme))
            written.append(figure_batch_collapse(curve, n_exp, theme))
    for path in written:
        rep.note(f"wrote {path.relative_to(path.parents[2])}")


