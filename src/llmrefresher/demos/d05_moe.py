# 6. Sparsity does not survive a batch
# ---------------------------------------------------------------------------


def batch_collapse(rep: Report, model, logits: torch.Tensor) -> list[tuple[int, float]]:
    """How many distinct experts a group of tokens needs, as the group grows."""
    n_exp, top_k, layers = _cfg(model)
    _, idx = torch.topk(logits, top_k, dim=-1)  # (layers, tokens, k)
    n_tokens = idx.shape[1]

    sizes = [n for n in (1, 2, 4, 8, 16, 32, 64, 128, 256) if n <= n_tokens]
    curve = []
    rows = []
    for n in sizes:
        touched = expert_union(idx, n)
        curve.append((n, touched))
        rows.append(
            [n, f"{touched:.1f}", f"{100 * touched / n_exp:.0f}%", f"{n * top_k}"]
        )
    rep.table(
        ["tokens together", "experts needed", "of 64", "expert-slots used"], rows
    )

    # How the batch is computed: one call per expert, on the tokens routed to it.
    per_expert = torch.bincount(idx[0].flatten().cpu(), minlength=n_exp)
    called = per_expert[per_expert > 0]
    rep.blank()
    rep.note(f"Computing all {n_tokens} tokens at once, layer 0 makes one call per expert:")
    rep.blank()
    rep.kv("experts called", f"{len(called)} of {n_exp}")
    rep.kv("tokens per call, fewest", int(called.min()))
    rep.kv("tokens per call, median", int(called.median()))
    rep.kv("tokens per call, most", int(called.max()))
    rep.kv(f"tokens x {top_k} routing slots", f"{int(per_expert.sum()):,}")
    rep.takeaway(
        f"One token needs {top_k} experts; {curve[-1][0]} tokens together need "
        f"{curve[-1][1]:.0f}. Sparsity is a property of a token, not of a batch — "
        f"which is why an MoE saves arithmetic but not memory."
    )
    return curve


def batch_composition(
    rep: Report, model, same_idx: torch.Tensor, mixed_idx: torch.Tensor
) -> None:
    """Does a batch drawn from several domains need more experts than one domain?

    The curve above is measured on a single English passage, which is the
    friendly case: §4 showed that different kinds of text route differently, so
    a batch that mixes them should need more of the experts, not fewer. Both
    columns here are built the same way -- three passages routed as separate
    requests, then interleaved -- so the only difference between them is
    whether those three passages share a domain.
    """
    rows = []
    for n in (2, 4, 8, 16, 32, 64, 128, 256):
        if n > same_idx.shape[1]:
            break
        one = expert_union(same_idx, n)
        mix = expert_union(mixed_idx, n)
        rows.append([n, f"{one:.1f}", f"{mix:.1f}", f"{mix - one:+.1f}"])
    rep.table(
        ["tokens together", "one domain", "three domains", "difference"], rows
    )
    biggest = max(rows, key=lambda r: float(r[3]))
    rep.takeaway(
        f"Mixing domains needs more experts, not fewer: at {biggest[0]} tokens "
        f"together, {biggest[2]} of 64 against {biggest[1]}. Measuring on one "
        f"passage understates how fast sparsity goes."
    )


