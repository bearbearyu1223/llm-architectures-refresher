def _cfg(model) -> tuple[int, int, int]:
    c = model.config
    return c.num_experts, c.num_experts_per_tok, c.num_hidden_layers


# ---------------------------------------------------------------------------
# 1. Where the parameters are
# ---------------------------------------------------------------------------


def where_the_parameters_are(rep: Report, model) -> None:
    """Census by role, so 'the experts are the MLP' is a number, not a claim."""
    buckets = {"experts": 0, "router": 0, "attention": 0, "embed + head": 0, "norms": 0}
    for name, p in model.named_parameters():
        n = p.numel()
        if ".experts." in name:
            buckets["experts"] += n
        elif ".mlp.gate." in name:
            buckets["router"] += n
        elif ".self_attn." in name:
            buckets["attention"] += n
        elif "embed_tokens" in name or "lm_head" in name:
            buckets["embed + head"] += n
        else:
            buckets["norms"] += n

    total = sum(buckets.values())

    def count(n: int) -> str:
        # A row that rounds to 0.000B tells the reader nothing; the router and
        # the norms are small, not absent, and the post makes a point of it.
        return f"{n / 1e9:.3f}B" if n >= 5e7 else f"{n / 1e6:.2f}M"

    def share(n: int) -> str:
        pct = 100 * n / total
        return f"{pct:.1f}%" if pct >= 1 else f"{pct:.3f}%"

    rows = [
        [role, count(n), share(n)]
        for role, n in sorted(buckets.items(), key=lambda kv: -kv[1])
    ]
    rows.append(["TOTAL", count(total), "100.0%"])
    rep.table(["role", "parameters", "share"], rows)

    n_exp, top_k, layers = _cfg(model)
    per_expert = buckets["experts"] // (n_exp * layers)
    active_experts = per_expert * top_k * layers
    active = active_experts + buckets["attention"] + buckets["norms"] + buckets["embed + head"] // 2

    rep.blank()
    rep.kv("experts per layer", n_exp)
    rep.kv("experts used per token", top_k)
    rep.kv("parameters in one expert", f"{per_expert / 1e6:.2f}M")
    rep.kv("total parameters", f"{total / 1e9:.3f}B")
    rep.kv("active parameters per token", f"{active / 1e9:.3f}B")
    rep.kv("active share", f"{100 * active / total:.1f}%")
    rep.takeaway(
        f"{100 * buckets['experts'] / total:.0f}% of the weights are experts, and a token "
        f"touches {top_k} of {n_exp} of them. The model is mostly a thing it "
        f"declines to use."
    )


