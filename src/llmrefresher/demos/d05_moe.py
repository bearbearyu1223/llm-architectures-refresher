def _load(device: torch.device):
    """OLMoE-1B-7B in bf16. Cached locally; no network access at run time."""
    from transformers import AutoModelForCausalLM
    from transformers.utils import logging as hf_logging

    # The weight-loading progress bar writes to stdout, which lands in the
    # captured output the post pastes from. Silence it: this demo's stdout is a
    # document, not a terminal.
    hf_logging.disable_progress_bar()
    model = AutoModelForCausalLM.from_pretrained(MODEL, dtype=torch.bfloat16)
    model.eval()
    # Move device-then-dtype separately, never fused: torch 2.13's MPS backend
    # reinterprets bits rather than converting on a fused .to(device, dtype).
    model.to(device)
    return model


