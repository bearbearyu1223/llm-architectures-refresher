def main() -> None:
    torch.manual_seed(0)
    rep = Report("05", "Mixture-of-experts: routing, and what sparsity costs")
    rep.header()

    device = get_device()
    model = _load(device)
    tok = _tokenizer()
    n_exp, top_k, layers = _cfg(model)

    ids = tok(PROSE, return_tensors="pt").input_ids.to(device)
    rep.kv("model", MODEL)
    rep.kv("layers", layers)
    rep.kv("experts per layer", n_exp)
    rep.kv("experts per token", top_k)
    rep.kv("dtype", "bfloat16")
    rep.kv("routing passage", f"{ids.shape[1]} tokens")

    counts = {"experts": 0, "router": 0, "attention": 0, "embed + head": 0, "norms": 0}
    for name, p in model.named_parameters():
        n = p.numel()
        if ".experts." in name:
            counts["experts"] += n
        elif ".mlp.gate." in name:
            counts["router"] += n
        elif ".self_attn." in name:
            counts["attention"] += n
        elif "embed_tokens" in name or "lm_head" in name:
            counts["embed + head"] += n
        else:
            counts["norms"] += n

    rep.section("1. Where the parameters actually are               [post §1]")
    where_the_parameters_are(rep, model)

    rep.section("2. The router is the smallest part of the model    [post §2]")
    the_router_is_tiny(rep, model)

    logits = route(model, ids)

    rep.section("3. One token, routed                               [post §3]")
    chosen = one_token_routed(rep, model, tok, logits, ids)
    rep.blank()
    routing_depth_profile(rep, model, logits, tok, ids)

    rep.section("4. What the router learns                          [post §4]")
    usage, halves = what_the_router_learns(rep, model, tok)

    rep.section("5. Two bills: memory and time                      [post §5]")
    two_bills(rep, model, ids, device)

    # Sections 6 and 7 both climb with sample size, so they get a longer
    # passage: on 94 tokens they would report a property of the passage.
    long_ids = tok(LONG_PROSE, return_tensors="pt").input_ids.to(device)
    long_logits = route(model, long_ids)

    rep.section("6. Sparsity does not survive a batch               [post §6]")
    rep.kv("passage", f"{long_ids.shape[1]} tokens")
    rep.blank()
    curve = batch_collapse(rep, model, long_logits)

    rep.section("7. Nothing balances the load for free              [post §7]")
    rep.kv("passage", f"{long_ids.shape[1]} tokens")
    rep.kv("routing slots per layer", f"{long_ids.shape[1] * top_k}")
    rep.blank()
    load_balance(rep, model, long_logits)

    rep.section("8. Figures")
    make_figures(rep, model, counts, usage, halves, curve, chosen)


if __name__ == "__main__":
    main()
