def two_bills(rep: Report, model, ids: torch.Tensor, device: torch.device) -> dict:
    """Memory is set by total parameters; time is set by active ones."""
    n_exp, top_k, layers = _cfg(model)
    total = sum(p.numel() for p in model.parameters())

    rep.kv("weights resident (bf16)", f"{total * 2 / GIB:.2f} GiB")
    rep.note("  every expert must be in memory; the router picks at run time,")
    rep.note("  so there is no subset you could have left on disk.")
    rep.blank()

    # Same weights, same memory, k changed: the cleanest isolation of "active
    # parameters" there is. Everything else about the forward pass is identical.
    # This is a timing experiment only -- with norm_topk_prob=False, routing to
    # all 64 experts changes what the model computes, so the top-64 row is a
    # measurement of cost, never of quality.
    def set_k(k: int) -> None:
        model.config.num_experts_per_tok = k
        for m in model.modules():
            if hasattr(m, "top_k"):
                m.top_k = k

    # Every later section routes top-8. If the benchmark raised while top-64 was
    # set, they would silently measure a different model, so restore in finally.
    # More repeats do not steady the ratio: 5 trials each at 5 and at 10 repeats
    # gave standard deviations of 0.021 and 0.027. Run-to-run drift is the machine.
    timings = {}
    try:
        for k in (top_k, n_exp):
            set_k(k)
            with torch.no_grad():
                timings[k] = benchmark_ms(lambda: model(ids), device=device, warmup=2, repeats=5)
    finally:
        set_k(top_k)
    rep.table(
        ["experts per token", "forward (ms)", "vs top-8"],
        [
            [top_k, f"{timings[top_k]:.1f}", "1.00x"],
            [n_exp, f"{timings[n_exp]:.1f}", f"{timings[n_exp] / timings[top_k]:.2f}x"],
        ],
    )
    rep.blank()
    rep.kv("expert FLOPs ratio (64/8)", f"{n_exp / top_k:.0f}x")
    rep.kv("measured wall-clock ratio", f"{timings[n_exp] / timings[top_k]:.2f}x")
    rep.note("  below 8x because attention, norms and the LM head are unchanged")
    rep.takeaway(
        f"Turning every expert on costs {timings[n_exp] / timings[top_k]:.1f}x the time "
        f"and 0 extra bytes of weights. Memory is billed on {total / 1e9:.1f}B "
        f"parameters no matter which {top_k} get used."
    )
    return timings


