def figure_token_flow(logits: torch.Tensor, token_text: str, n_exp: int, top_k: int,
                      hid: int, theme: Theme, layer: int = 0, pos: int = 1) -> Path:
    """One token through one MoE layer, top to bottom, with the math beside each step.

    Three lanes, kept apart so nothing crosses: formulas on the left, the data in
    the middle, this token's real numbers on the right. The steps are the ones in
    section 3's two formula blocks, in order, and every number is computed from the
    same logits section 3's table prints.
    """
    z = logits[layer, pos]
    p = torch.softmax(z, dim=-1)
    top_w, top_e = torch.topk(p, top_k)
    chosen = [int(e) for e in top_e.tolist()]
    kept = top_w.sum().item()
    zmin_e = int(torch.argmin(z))

    W, H = 12.0, 15.0
    fig = plt.figure(figsize=(W, H))
    ax = fig.add_axes([0, 0, 1, 1])
    ax.set_xlim(0, W); ax.set_ylim(0, H); ax.axis("off"); ax.grid(False)

    L_RIGHT = 4.05            # left lane: text right-aligned here
    C_LEFT, C_RIGHT = 4.55, 9.15
    CX = (C_LEFT + C_RIGHT) / 2
    R_LEFT = 9.55             # right lane: text left-aligned here
    SKIP_X = 9.35             # residual line, between centre and right lanes
    FEED_X = 4.35             # x feeding the experts, between left and centre lanes
    orange = theme.series[1]
    arrow_kw = {"arrowstyle": "-|>", "color": theme.secondary, "lw": 1.3, "shrinkA": 0, "shrinkB": 0}

    def arrow(x1, y1, x2, y2):
        ax.annotate("", xy=(x2, y2), xytext=(x1, y1), arrowprops=arrow_kw, zorder=1)

    def line(xs, ys, **kw):
        ax.plot(xs, ys, color=kw.pop("color", theme.secondary), lw=1.3, zorder=1,
                solid_capstyle="butt", **kw)

    def badge(x, y, n):
        # Outlined, so they cannot be confused with the filled expert boxes.
        ax.add_patch(patches.Circle((x, y), 0.19, facecolor=theme.surface,
                                    edgecolor=orange, lw=1.6, zorder=3))
        ax.text(x, y, str(n), ha="center", va="center", fontsize=11,
                fontweight="bold", color=orange, zorder=4)

    def step(y, n, title, math):
        badge(0.55, y + 0.16, n)
        ax.text(L_RIGHT, y + 0.16, title, ha="right", va="center", fontsize=12.5,
                fontweight="bold", color=theme.ink)
        ax.text(L_RIGHT, y - 0.30, math, ha="right", va="center", fontsize=14,
                color=theme.ink)

    def describe(y, name, lines):
        ax.text(R_LEFT, y + 0.17, name, ha="left", va="center", fontsize=12,
                fontweight="bold", color=theme.ink)
        ax.text(R_LEFT, y - 0.02, lines, ha="left", va="top", fontsize=10.5,
                color=theme.secondary, linespacing=1.45)

    def strip(y, cells, width, fill, h=0.34, values=None):
        x0 = CX - width / 2
        cw = width / cells
        for i in range(cells):
            fc = fill if values is None else values[i]
            ax.add_patch(patches.Rectangle((x0 + i * cw, y - h / 2), cw, h, facecolor=fc,
                                           edgecolor=theme.surface if values is not None else theme.axis,
                                           lw=0.5, zorder=2))
        return x0, x0 + width

    # Widths ordered like the numbers they stand for: 2,048 > 64. Not to scale.
    WIDE, MID = 4.4, 3.2
    y = H - 0.75
    ax.text(W / 2, y + 0.25, f"One token through one MoE layer: {token_text!r}, layer {layer}",
            ha="center", va="center", fontsize=14, fontweight="bold", color=theme.ink)
    ax.text(W / 2, y - 0.12, "the math on the left, the data in the middle, this token's "
            "numbers on the right  ·  strip widths in order, not to scale",
            ha="center", va="center", fontsize=9.5, color=theme.secondary)

    # ---- h_mid ----------------------------------------------------------------
    y_h = H - 1.75
    strip(y_h, 32, WIDE, theme.ramp[0])
    describe(y_h, "$h_{mid}$", f"the residual stream after\nattention: {hid:,} numbers")

    # ---- step 1: normalize -----------------------------------------------------
    y_x = y_h - 1.55
    arrow(CX, y_h - 0.19, CX, y_x + 0.19)
    step((y_h + y_x) / 2, 1, "normalize", r"$x = \mathrm{RMSNorm}(h_{mid})$")
    strip(y_x, 32, WIDE, theme.ramp[1])
    describe(y_x, "$x$", f"{hid:,} numbers, rescaled\nto a standard size")

    # ---- step 2: score ---------------------------------------------------------
    y_z = y_x - 1.55
    arrow(CX, y_x - 0.19, CX, y_z + 0.19)
    step((y_x + y_z) / 2, 2, f"score all {n_exp} experts", r"$z = W_r\,x$")
    ax.text(CX + 0.12, (y_x + y_z) / 2, f"$W_r$: {n_exp} rows, each {hid:,} wide",
            ha="left", va="center", fontsize=10.5, color=theme.secondary)
    cmap = sequential_cmap(theme)
    zn = ((z - z.min()) / (z.max() - z.min())).tolist()
    strip(y_z, n_exp, MID, None, values=[mcolors.to_hex(cmap(v)) for v in zn])
    describe(y_z, "$z$, the logits",
             f"{n_exp} raw scores, any sign;\ndarker cells score higher\nhighest $z_{{{chosen[0]}}}$ = {z[chosen[0]]:+.4f}"
             f"\nlowest $z_{{{zmin_e}}}$ = {z[zmin_e]:+.4f}".replace("-", "\u2212"))

    # ---- step 3: softmax -------------------------------------------------------
    y_p = y_z - 1.85
    arrow(CX, y_z - 0.19, CX, y_p + 0.42)
    step((y_z + y_p) / 2 + 0.05, 3, "turn scores into probabilities",
         rf"$p_e = e^{{z_e}} \,/\, \sum_{{j=1}}^{{{n_exp}}} e^{{z_j}}$")
    x0 = CX - MID / 2
    cw = MID / n_exp
    top = set(chosen)
    peak = p.max().item()
    for i in range(n_exp):
        hgt = 0.80 * p[i].item() / peak
        ax.add_patch(patches.Rectangle((x0 + i * cw + cw * 0.12, y_p - 0.40), cw * 0.76, hgt,
                                       facecolor=theme.ramp[5] if i in top else theme.ramp[1],
                                       edgecolor="none", zorder=2))
    line([x0, x0 + MID], [y_p - 0.40, y_p - 0.40], color=theme.axis)
    describe(y_p + 0.2, "$p$, the probabilities",
             f"all {n_exp} sum to 1\nlargest $p_{{{chosen[0]}}}$ = {top_w[0]:.4f}")

    # ---- step 4: keep the top k -----------------------------------------------
    y_k = y_p - 1.05
    y_bus = y_k - 0.62
    arrow(CX, y_p - 0.40, CX, y_k + 0.21)
    kw_ = 3.3
    ax.add_patch(patches.FancyBboxPatch((CX - kw_ / 2, y_k - 0.21), kw_, 0.42,
                                        boxstyle="round,pad=0,rounding_size=0.08",
                                        facecolor=theme.surface, edgecolor=theme.series[0], lw=1.3, zorder=2))
    ax.text(CX, y_k, r"$\mathcal{K}$ = {" + ", ".join(str(e) for e in chosen) + "}",
            ha="center", va="center", fontsize=11, color=theme.ink, zorder=3)
    step(y_k + 0.05, 4, f"keep the top {top_k}", rf"$\mathcal{{K}}$ = the {top_k} largest $p_e$")
    describe(y_k + 0.05, r"$\mathcal{K}$, the chosen experts",
             f"picks which experts run;\nthe other {n_exp - top_k} are skipped")

    # ---- step 5: run the chosen experts ---------------------------------------
    bw, gap = 0.565, 0.035
    row_w = top_k * bw + (top_k - 1) * gap
    bx = [CX - row_w / 2 + i * (bw + gap) + bw / 2 for i in range(top_k)]
    y_e = y_bus - 0.85
    # x feeds every chosen expert: from the x strip, down the lane left of centre.
    line([CX - WIDE / 2, FEED_X], [y_x, y_x])
    line([FEED_X, FEED_X], [y_x, y_bus])
    ax.text(FEED_X - 0.07, (y_z + y_p) / 2 - 0.1, "the same $x$ goes to every chosen expert",
            rotation=90, ha="right", va="center", fontsize=9.5, color=theme.secondary)
    line([FEED_X, bx[-1]], [y_bus, y_bus])
    for cx_ in bx:
        arrow(cx_, y_bus, cx_, y_e + 0.30)
    for cx_, e in zip(bx, chosen, strict=True):
        ax.add_patch(patches.FancyBboxPatch((cx_ - bw / 2, y_e - 0.30), bw, 0.60,
                                            boxstyle="round,pad=0,rounding_size=0.06",
                                            facecolor=theme.ramp[5], edgecolor=theme.ramp[5], zorder=2))
        ax.text(cx_, y_e, f"$\\mathrm{{FFN}}_{{{e}}}$", ha="center", va="center", fontsize=10,
                color=ink_for(theme.ramp[5]), zorder=3)
    step(y_e, 5, "run each chosen expert",
         r"$\mathrm{FFN}_e(x) = W_{down}\,(\mathrm{SiLU}(W_{gate}\,x) \odot W_{up}\,x)$")
    describe(y_e + 0.1, "8 expert outputs", f"each {hid:,} numbers")

    # ---- step 6: scale by the weight ------------------------------------------
    y_w = y_e - 1.25
    for cx_, w in zip(bx, top_w.tolist(), strict=True):
        arrow(cx_, y_e - 0.30, cx_, y_w + 0.20)
        ax.add_patch(patches.FancyBboxPatch((cx_ - bw / 2, y_w - 0.20), bw, 0.40,
                                            boxstyle="round,pad=0,rounding_size=0.05",
                                            facecolor=theme.surface, edgecolor=orange, lw=1.1, zorder=2))
        ax.text(cx_, y_w, f"×{w:.4f}", ha="center", va="center", fontsize=7.8,
                color=theme.ink, zorder=3)
    step(y_w, 6, "weight each by its probability", r"$p_e \cdot \mathrm{FFN}_e(x)$")
    describe(y_w + 0.1, "the weights",
             f"sum to {kept:.4f}, not 1:\nOLMoE does not rescale them")

    # ---- step 7: add them up ---------------------------------------------------
    y_sum = y_w - 1.35
    y_mbus = y_w - 0.62
    for cx_ in bx:
        line([cx_, cx_], [y_w - 0.20, y_mbus])
    line([bx[0], bx[-1]], [y_mbus, y_mbus])
    arrow(CX, y_mbus, CX, y_sum + 0.24)
    ax.add_patch(patches.Circle((CX, y_sum), 0.24, facecolor=theme.surface,
                                edgecolor=theme.secondary, lw=1.3, zorder=2))
    ax.text(CX, y_sum, r"$\Sigma$", ha="center", va="center", fontsize=13, color=theme.ink, zorder=3)
    step(y_sum, 7, "add the eight together",
         r"$y = \sum_{e \in \mathcal{K}}\; p_e \cdot \mathrm{FFN}_e(x)$")
    describe(y_sum + 0.1, "$y$", f"{hid:,} numbers: the MoE output")

    # ---- step 8: residual ------------------------------------------------------
    y_plus = y_sum - 1.20
    arrow(CX, y_sum - 0.24, CX, y_plus + 0.22)
    ax.add_patch(patches.Circle((CX, y_plus), 0.22, facecolor=theme.surface,
                                edgecolor=theme.secondary, lw=1.3, zorder=2))
    ax.text(CX, y_plus, "+", ha="center", va="center", fontsize=15, color=theme.ink, zorder=3)
    # h_mid skips the whole block, down the lane right of centre.
    line([CX + WIDE / 2, SKIP_X], [y_h, y_h])
    line([SKIP_X, SKIP_X], [y_h, y_plus])
    arrow(SKIP_X, y_plus, CX + 0.22, y_plus)
    step(y_plus, 8, "add back into the stream", r"$h_{out} = h_{mid} + y$")
    y_o = y_plus - 1.05
    arrow(CX, y_plus - 0.22, CX, y_o + 0.19)
    strip(y_o, 32, WIDE, theme.ramp[0])
    describe(y_o, "$h_{out}$", f"{hid:,} numbers, on to layer {layer + 1}")

    return save_both(fig, SLUG, "token-flow", theme)


def figure_router_flow(model, logits: torch.Tensor, theme: Theme,
                       layer: int = 0, pos: int = 1) -> Path:
    """The router as a shape walkthrough, then the same token's real numbers.

    The top row is the pipeline in tensor shapes, which is the form post 1 used
    for attention. The bottom is all 64 probabilities for one actual token, so
    the reader can see *why* the kept mass is a fraction rather than being told.
    """
    n_exp, top_k, layers = _cfg(model)
    hid = model.config.hidden_size
    row = logits[layer, pos]
    probs = torch.softmax(row, dim=-1)
    top_w, top_e = torch.topk(probs, top_k)
    kept = top_w.sum().item()

    fig = plt.figure(figsize=(12.5, 8.2))
    ax_flow = fig.add_axes([0.02, 0.575, 0.96, 0.355])
    ax_bar = fig.add_axes([0.075, 0.085, 0.895, 0.405])
    for ax in (ax_flow, ax_bar):
        ax.grid(False)
    ax_flow.set_xlim(0, 1); ax_flow.set_ylim(0, 1); ax_flow.axis("off")

    def grid(ax, cx, cy, cols, rows_n, w, h, fill, edge=None):
        cw, chh = w / cols, h / rows_n
        for r in range(rows_n):
            for c in range(cols):
                ax.add_patch(patches.Rectangle(
                    (cx - w / 2 + c * cw, cy + h / 2 - (r + 1) * chh), cw, chh,
                    linewidth=0.6, edgecolor=edge or theme.axis, facecolor=fill, zorder=2))

    def caption(ax, cx, title, shape, y_title=0.325, y_shape=0.255):
        ax.text(cx, y_title, title, ha="center", fontsize=10,
                fontweight="bold", color=theme.ink)
        ax.text(cx, y_shape, shape, ha="center", va="top", fontsize=9,
                color=theme.secondary, linespacing=1.5)

    def op(ax, x1, x2, label, sub):
        y = 0.60
        ax.annotate("", xy=(x2, y), xytext=(x1, y),
                    arrowprops=dict(arrowstyle="-|>", color=theme.secondary, lw=1.3))
        mid = (x1 + x2) / 2
        ax.text(mid, y + 0.115, label, ha="center", fontsize=9.5,
                fontweight="bold", color=theme.series[1])
        ax.text(mid, y + 0.035, sub, ha="center", fontsize=8.5, color=theme.secondary)

    # Drawn widths must at least be *ordered* like the widths they label:
    # 2,048 > 64 > 8. An earlier version drew the 2,048-wide grid narrower than
    # the 64-wide one, which is the figure contradicting its own captions.
    # Exact proportion is impossible (2,048 is 256x 8), and the subtitle says so.
    widths = [(0.200, 12), (0.100, 6), (0.100, 6), (0.030, 2)]   # (drawn, columns)
    lefts = [0.015, 0.375, 0.635, 0.895]
    xs = [l + w / 2 for l, (w, _) in zip(lefts, widths, strict=True)]
    rights = [l + w for l, (w, _) in zip(lefts, widths, strict=True)]
    fills = [theme.ramp[1], theme.ramp[2], theme.ramp[4], theme.ramp[5]]
    for x, (w, cols), fill in zip(xs, widths, fills, strict=True):
        grid(ax_flow, x, 0.60, cols, 4, w, 0.30, fill)
    pad = 0.012
    caption(ax_flow, xs[0], "token vectors", f"n tokens × {hid:,} wide")
    op(ax_flow, rights[0] + pad, lefts[1] - pad, "router matrix",
       f"{n_exp} rows, each {hid:,} wide")
    caption(ax_flow, xs[1], "routing logits", f"n tokens × {n_exp} wide\nraw scores")
    op(ax_flow, rights[1] + pad, lefts[2] - pad, "softmax",
       f"over all {n_exp}, each row sums to 1")
    caption(ax_flow, xs[2], "routing probabilities", f"n tokens × {n_exp} wide")
    op(ax_flow, rights[2] + pad, lefts[3] - pad, f"keep top {top_k}",
       "discard the rest")
    caption(ax_flow, xs[3], "chosen experts", f"n tokens × {top_k} wide\n+ their weights")

    ax_flow.text(0.5, 0.965, "How the router picks, in shapes",
                 ha="center", fontsize=12.5, fontweight="bold", color=theme.ink)
    ax_flow.text(0.5, 0.895, "n is however many tokens are being processed together; "
                 "every row is routed independently; widths are in order, not to scale",
                 ha="center", fontsize=9, color=theme.secondary)

    # ---- the same thing, for one real token ------------------------------
    keep = set(int(e) for e in top_e.tolist())
    colors = [theme.ramp[5] if e in keep else theme.ramp[1] for e in range(n_exp)]
    ax_bar.bar(range(n_exp), probs.numpy() * 100, color=colors, width=0.78,
               edgecolor="none")
    ax_bar.set_xlim(-1, n_exp)
    ax_bar.set_xlabel(f"expert (layer {layer})", color=theme.secondary)
    ax_bar.set_ylabel("routing probability (%)", color=theme.secondary)
    ax_bar.set_title(
        f"All {n_exp} probabilities for one token, and the {top_k} that survive the cut",
        color=theme.ink)
    for s in ("top", "right"):
        ax_bar.spines[s].set_visible(False)
    ax_bar.spines["left"].set_color(theme.axis)
    ax_bar.spines["bottom"].set_color(theme.axis)
    ax_bar.tick_params(colors=theme.muted)
    for lbl in ax_bar.get_xticklabels() + ax_bar.get_yticklabels():
        lbl.set_color(theme.secondary)
    ax_bar.set_axisbelow(True)
    ax_bar.yaxis.grid(True, color=theme.grid, linewidth=0.8)

    # The totals describe two *groups* of bars. A leader line to the tallest bar
    # made "kept: 0.4281" read as that one expert's weight, so the totals live in
    # a legend keyed by fill instead, where they cannot attach to a single bar.
    from matplotlib.patches import Patch
    ax_bar.legend(
        handles=[
            Patch(facecolor=theme.ramp[5], label=f"the {top_k} kept, together {kept:.4f}"),
            Patch(facecolor=theme.ramp[1],
                  label=f"the {n_exp - top_k} discarded, together {1 - kept:.4f}"),
        ],
        loc="upper right", fontsize=9.5, labelcolor=theme.ink, frameon=False,
        title="kept weights are not rescaled to sum to 1",
        title_fontsize=9,
    )
    ax_bar.get_legend().get_title().set_color(theme.secondary)
    return save_both(fig, SLUG, "router-flow", theme)


def figure_where_the_weights_are(rep_counts: dict, theme: Theme) -> Path:
    """Ink measures the quantity: one bar, split by role."""
    fig, ax = plt.subplots(figsize=(9.5, 2.9))
    total = sum(rep_counts.values())
    order = sorted(rep_counts.items(), key=lambda kv: -kv[1])
    small = [r for r, n in order if 100 * n / total <= 8]
    left = 0.0
    for i, (role, n) in enumerate(order):
        share = 100 * n / total
        fill = theme.ramp[5] if role == "experts" else theme.ramp[max(0, 3 - i)]
        ax.barh([0], [share], left=[left], height=0.55, color=fill,
                edgecolor=theme.surface, linewidth=1.2)
        if share > 8:
            ax.text(left + share / 2, 0, f"{role}\n{share:.1f}%", ha="center",
                    va="center", fontsize=11, color=ink_for(fill))
        else:
            # Too narrow to label inside, and every small segment is crowded into
            # the last few percent of the bar -- so labels go on a spread-out row
            # below with a leader back to the segment they name.
            # All on one row. Leaders run from segments in left-to-right order to
            # labels in the same order, and two such lines cannot cross; the
            # alternating two-row layout this replaces crossed router over embed.
            pct = f"{share:.1f}%" if share >= 0.1 else f"{share:.3f}%"
            slot = small.index(role)
            label_x = 40 + 18 * slot
            y_txt = -0.80
            ax.annotate(
                f"{role}\n{pct}",
                xy=(left + share / 2, -0.30),
                xytext=(label_x, y_txt),
                ha="center", va="center", fontsize=9, color=theme.secondary,
                arrowprops=dict(arrowstyle="-", color=theme.axis, lw=0.8,
                                shrinkA=2, shrinkB=2),
            )
        left += share
    ax.set_xlim(0, 100); ax.set_ylim(-1.25, 0.45)
    ax.set_yticks([]); ax.set_xlabel("share of all parameters (%)")
    ax.grid(False)
    for s in ("left", "right", "top"):
        ax.spines[s].set_visible(False)
    ax.set_title("Where OLMoE-1B-7B's 6.9B parameters live", color=theme.ink)
    fig.tight_layout()
    return save_both(fig, SLUG, "weight-census", theme)


def figure_specialization(
    usage: dict[str, torch.Tensor],
    halves: dict[str, tuple[torch.Tensor, torch.Tensor]],
    theme: Theme,
) -> Path:
    """Expert usage per domain in the last layer — the specialization claim.

    The top two rows are the two halves of the *same* prose passage. They are
    what sampling noise looks like, and they are in the figure so the reader can
    tell the cross-domain rows apart from it by eye rather than on trust.
    """

    last = usage["prose"].shape[0] - 1
    rows = [
        ("prose, 1st half", halves["prose"][0][last]),
        ("prose, 2nd half", halves["prose"][1][last]),
        ("code", usage["code"][last]),
        ("math", usage["math"][last]),
    ]
    names = [n for n, _ in rows]
    data = torch.stack([v for _, v in rows]).numpy()

    fig, ax = plt.subplots(figsize=(10.5, 3.7))
    im = ax.imshow(data * 100, aspect="auto", cmap=sequential_cmap(theme),
                   interpolation="nearest")
    ax.set_yticks(range(len(names)), names)
    # Separate the noise-floor pair from the cross-domain rows.
    ax.axhline(1.5, color=theme.surface, lw=3.0)
    ax.set_xlabel(f"expert (layer {last})")
    ax.set_title("The same 64 experts, used differently by different text",
                 color=theme.ink, pad=26)
    # Without this line a reader has no way to know why one passage appears as
    # two rows, and those two rows are the entire basis of the comparison.
    ax.text(0.5, 1.035, "top two rows: one prose passage split in half, which is what "
            "noise looks like  ·  bottom two: different kinds of text",
            transform=ax.transAxes, ha="center", va="bottom", fontsize=9,
            color=theme.secondary)
    ax.axhline(1.5, color=theme.ink, lw=1.0)
    ax.grid(False)
    cb = fig.colorbar(im, ax=ax, pad=0.015)
    cb.set_label("% of routing slots\n(8 per token)", color=theme.secondary)
    cb.ax.tick_params(colors=theme.muted)
    cb.outline.set_visible(False)
    fig.tight_layout()
    return save_both(fig, SLUG, "specialization", theme)


def figure_batch_collapse(
    curve: list[tuple[int, float]], n_exp: int, top_k: int, theme: Theme
) -> Path:
    """Experts needed against tokens processed together."""
    fig, ax = plt.subplots(figsize=(8.5, 4.6))
    xs = [c[0] for c in curve]
    ys = [c[1] for c in curve]
    ax.axhline(n_exp, color=theme.muted, lw=1.2, ls="--")
    ax.text(xs[0], n_exp - 2.5, f"all {n_exp} experts", fontsize=9.5,
            color=theme.secondary, va="top")
    ax.plot(xs, ys, marker="o", color=theme.series[0], label="experts actually needed")
    # Stop the worst case where it reaches the ceiling. Drawn all the way along,
    # it lay on top of the dashed "all 64" line and hid it.
    worst = [(x, min(n_exp, top_k * x)) for x in xs]
    cut = next(i for i, (_, y) in enumerate(worst) if y >= n_exp) + 1
    ax.plot([x for x, _ in worst[:cut]], [y for _, y in worst[:cut]], marker="",
            ls=":", color=theme.series[1],
            label="if no two tokens ever shared an expert")
    ax.set_xscale("log", base=2)
    ax.set_xticks(xs, [str(x) for x in xs])
    ax.set_xlabel("tokens processed together")
    ax.set_ylabel("distinct experts required")
    ax.set_ylim(0, n_exp + 6)
    ax.set_title("Per-token sparsity does not survive batching", color=theme.ink)
    ax.legend(labelcolor=theme.secondary)
    fig.tight_layout()
    return save_both(fig, SLUG, "batch-collapse", theme)


def make_figures(
    rep: Report, model, counts: dict, usage: dict, halves: dict,
    curve: list, chosen: list[int], kept: float, logits: torch.Tensor, token_text: str,
) -> None:
    n_exp, top_k, _ = _cfg(model)
    written = []
    for theme in THEMES:
        with styled(theme):
            written.append(figure_architecture(model, chosen, kept, curve, theme))
            written.append(figure_block(model, chosen, theme))
            written.append(figure_token_flow(logits, token_text, n_exp, top_k,
                                             model.config.hidden_size, theme))
            written.append(figure_router_flow(model, logits, theme))
            written.append(figure_where_the_weights_are(counts, theme))
            written.append(figure_specialization(usage, halves, theme))
            written.append(figure_batch_collapse(curve, n_exp, top_k, theme))
    for path in written:
        rep.note(f"wrote {path.relative_to(path.parents[2])}")


